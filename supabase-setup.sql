-- Keep authenticated accounts from flooding the owner queue. The limit applies
-- across all three submission forms and is enforced by the database.
create or replace function public.enforce_submission_rate_limit()
returns trigger language plpgsql security definer set search_path = ''
as $$
declare
    recent_count integer;
begin
    perform pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtextextended(new.user_id::text, 0));
    select
        (select count(*) from public.signer_submissions where user_id = new.user_id and created_at >= now() - interval '24 hours') +
        (select count(*) from public.community_posts where user_id = new.user_id and created_at >= now() - interval '24 hours') +
        (select count(*) from public.showcase_stories where user_id = new.user_id and created_at >= now() - interval '24 hours')
    into recent_count;
    if recent_count >= 10 then
        raise exception 'Daily submission limit reached; please try again later';
    end if;
    return new;
end;
$$;
revoke all on function public.enforce_submission_rate_limit() from public, anon;
grant execute on function public.enforce_submission_rate_limit() to authenticated;
drop trigger if exists lc_signer_submission_rate_limit on public.signer_submissions;
create trigger lc_signer_submission_rate_limit before insert on public.signer_submissions
    for each row execute function public.enforce_submission_rate_limit();
drop trigger if exists lc_community_post_rate_limit on public.community_posts;
create trigger lc_community_post_rate_limit before insert on public.community_posts
    for each row execute function public.enforce_submission_rate_limit();
drop trigger if exists lc_showcase_story_rate_limit on public.showcase_stories;
create trigger lc_showcase_story_rate_limit before insert on public.showcase_stories
    for each row execute function public.enforce_submission_rate_limit();

